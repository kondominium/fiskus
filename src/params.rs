#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn zones_are_sorted_and_start_after_the_allowance() {
        for year in TaxYear::ALL {
            let zones = tariff_for(year);
            let allowance = for_year(year).basic_allowance.value_eur;
            for pair in zones.windows(2) {
                assert!(pair[0].from_eur < pair[1].from_eur, "{year:?}");
            }
            if let Some(first) = zones.first() {
                assert_eq!(first.from_eur, allowance + 1, "{year:?}");
            }
        }
    }

    #[test]
    fn every_zone_has_a_positive_step() {
        for year in TaxYear::ALL {
            assert!(tariff_for(year).iter().all(|zone| zone.step_eur > 0));
        }
    }

    #[test]
    fn a_year_has_a_source_exactly_when_it_has_zones() {
        for year in TaxYear::ALL {
            let sourced = tariff_source_for(year).is_some();
            assert_eq!(sourced, !tariff_for(year).is_empty(), "{year:?}");
        }
    }
}
