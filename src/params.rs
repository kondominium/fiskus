#[cfg(test)]
mod tests {
    use super::*;
    use crate::TaxYear;

    #[test]
    fn every_year_has_zones_sorted() {
        for year in TaxYear::ALL {
            let zones = tariff_for(year);
            assert!(!zones.is_empty(), "{year:?} has no zones");
            for w in zones.windows(2) {
                assert!(w[0].from_eur < w[1].from_eur, "{year:?} zones not sorted");
            }
        }
    }

    #[test]
    fn every_year_has_positive_basic_allowance() {
        for year in TaxYear::ALL {
            assert!(basic_allowance_placeholder(year) >= 0);
        }
    }

    #[test]
    fn tariff_source_is_populated() {
        for year in TaxYear::ALL {
            let s = tariff_source_for(year);
            assert!(!s.citation.is_empty(), "{year:?} citation empty");
            assert!(!s.source.is_empty(), "{year:?} source empty");
            assert!(!s.reference.is_empty(), "{year:?} reference empty");
        }
    }

    #[test]
    fn for_year_basic_allowance_matches() {
        for year in TaxYear::ALL {
            let p = for_year(year);
            assert_eq!(
                p.basic_allowance.value_eur,
                crate::basic_allowance_eur(year)
            );
        }
    }

    // helper: basic allowance via params::for_year
    fn basic_allowance_placeholder(year: TaxYear) -> i128 {
        for_year(year).basic_allowance.value_eur
    }

    use proptest::prelude::*;

    proptest! {
        #[test]
        fn random_year_has_zones(index in 0..TaxYear::ALL.len()) {
            let year = TaxYear::ALL[index];
            prop_assert!(!tariff_for(year).is_empty());
        }
    }
}
